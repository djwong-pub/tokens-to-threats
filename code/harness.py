#!/usr/bin/env python3
"""Code-suite harness: run every verified script, capture evidence, write RESULTS.md.

Rules a script must satisfy to appear as PASS in ./code/RESULTS.md:
  * exit code 0 within the time budget;
  * at least one ``PASS <name>`` line (the script's own assertion summary);
  * no ``FAIL`` line;
  * optional ``METRIC key=value`` lines, which are carried into the results table.

The harness never inspects plots and never trusts a print: the assertions live in the
script, and the harness re-checks the exit status. Raw stdout/stderr per script is kept
in ./code/logs/ so that any number in RESULTS.md can be traced to the run that produced it.

Usage:
  ./.venv/bin/python code/harness.py                 # run everything
  ./.venv/bin/python code/harness.py ch01            # only scripts matching 'ch01'
"""
from __future__ import annotations

import datetime as dt
import os
import re
import subprocess
import sys
import time

CODE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(CODE)
LOGS = os.path.join(CODE, "logs")
RESULTS = os.path.join(CODE, "RESULTS.md")
SUITE_BUDGET_S = 30 * 60
PER_SCRIPT_BUDGET_S = 75  # scripts are tuned to finish <60 s on an idle CPU (the design constraint); the cap carries 15 s of slack so a loaded box fails on real drift, not on contention


# Verified scripts live in code/phaseNN_*/ directories. Everything at the top level of
# code/ is tooling (this harness, corpus/manifest generators), not a verified script.
TOOLING = {"harness.py", "citekeys.py", "make_bibliography.py", "make_chapters.py",
           "make_parts.py", "make_corpus_guide.py", "corpus_fetch.py",
           "corpus_list.py", "corpus_discover.py", "common.py"}


def discover(filter_substr: str = "") -> list[str]:
    found = []
    for dirpath, dirs, files in os.walk(CODE):
        dirs[:] = [d for d in dirs if d not in ("logs", "__pycache__", "corpus")]
        rel_dir = os.path.relpath(dirpath, CODE)
        if not re.match(r"^(phase\d+|ch\d+)", rel_dir):
            continue
        for f in sorted(files):
            if f.endswith(".py") and f not in TOOLING:
                rel = os.path.relpath(os.path.join(dirpath, f), CODE)
                if not filter_substr or filter_substr in rel:
                    found.append(rel)
    return sorted(found)


def run_script(rel: str) -> dict:
    os.makedirs(LOGS, exist_ok=True)
    env = dict(os.environ, PYTHONPATH=CODE, PYTHONHASHSEED="0", MPLBACKEND="Agg")
    t0 = time.time()
    try:
        # Absolute script path; cwd is the repo root so scripts can open corpus/figure paths.
        r = subprocess.run([sys.executable, os.path.join(CODE, rel)], cwd=ROOT, env=env,
                           capture_output=True, text=True, timeout=PER_SCRIPT_BUDGET_S)
        rc, out, err = r.returncode, r.stdout, r.stderr
    except subprocess.TimeoutExpired as e:
        rc, out, err = 124, (e.stdout or b"").decode(errors="replace"), "TIMEOUT"
    dt_s = time.time() - t0

    passes = re.findall(r"^PASS\s+(.+)$", out, flags=re.M)
    fails = re.findall(r"^FAIL\s+(.+)$", out, flags=re.M)
    metrics = dict(re.findall(r"^METRIC\s+([\w.:/ -]+?)\s*=\s*(\S+)$", out, flags=re.M))

    log_path = os.path.join(LOGS, rel.replace(os.sep, "__") + ".log")
    with open(log_path, "w") as fh:
        fh.write(f"# command: {os.path.basename(sys.executable)} {rel}\n"
                 f"# cwd: {ROOT}\n# exit: {rc}\n# seconds: {dt_s:.2f}\n\n")
        fh.write(out)
        if err.strip():
            fh.write("\n----- stderr -----\n" + err)

    ok = rc == 0 and passes and not fails
    return {"script": rel, "rc": rc, "s": dt_s, "ok": ok, "checks": len(passes),
            "pass_names": passes, "fail_names": fails, "metrics": metrics,
            "log": os.path.relpath(log_path, ROOT)}


def write_results(rows: list[dict], total_s: float) -> None:
    today = dt.date.today().isoformat()
    n_ok = sum(1 for r in rows if r["ok"])
    header = [
        "# Verified code suite — results",
        "",
        f"Generated by `code/harness.py` on {today}. Every row is a script that exits 0 and",
        "prints its own `PASS` assertions; raw stdout for each run is kept in `code/logs/`.",
        "",
        f"**{n_ok}/{len(rows)} scripts passed** in {total_s:.1f}s "
        f"(budget {SUITE_BUDGET_S // 60} min; per-script budget {PER_SCRIPT_BUDGET_S}s). "
        "CPU-only, seeded, no network.",
        "",
        "| script | status | checks | seconds | headline metrics |",
        "|---|---|---|---|---|",
    ]
    body = []
    for r in rows:
        m = r["metrics"]
        headline = ", ".join(f"`{k}`={v}" for k, v in list(m.items())[:4]) or "—"
        status = "PASS" if r["ok"] else f"**FAIL** (rc={r['rc']})"
        body.append(f"| `{r['script']}` | {status} | {r['checks']} | {r['s']:.1f} | {headline} |")
    tail = ["", "## Assertion detail", ""]
    for r in rows:
        tail.append(f"### `{r['script']}`")
        tail.append("")
        if not r["ok"]:
            tail.append(f"Exit code {r['rc']}; failing checks: {r['fail_names'] or 'none printed'}; "
                        f"log: `{r['log']}`")
            tail.append("")
            continue
        for p in r["pass_names"]:
            tail.append(f"- PASS {p}")
        tail.append("")
    with open(RESULTS, "w") as fh:
        fh.write("\n".join(header + body + tail) + "\n")


def main() -> int:
    filt = sys.argv[1] if len(sys.argv) > 1 else ""
    scripts = discover(filt)
    if not scripts:
        print(f"[harness] no scripts matched {filt!r}")
        return 1

    t0 = time.time()
    rows = []
    for rel in scripts:
        r = run_script(rel)
        rows.append(r)
        flag = "ok  " if r["ok"] else "FAIL"
        print(f"[{flag}] {rel:48s} {r['checks']:2d} checks  {r['s']:5.1f}s")
    total = time.time() - t0

    if filt:
        print(f"[harness] subset run ({filt}): not rewriting RESULTS.md")
    else:
        write_results(rows, total)
        print(f"[harness] wrote {os.path.relpath(RESULTS, ROOT)}")

    n_fail = sum(1 for r in rows if not r["ok"])
    print(f"[harness] {len(rows) - n_fail}/{len(rows)} passed in {total:.1f}s "
          f"({'within' if total <= SUITE_BUDGET_S else 'OVER'} suite budget)")
    return 1 if n_fail else 0


if __name__ == "__main__":
    raise SystemExit(main())
